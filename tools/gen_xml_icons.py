#!/usr/bin/env python3
"""Writes src/cui_xml_icons.h: the icons of include/cui/cui_icons.h under the
names a document writes, so XML can say Icon="audio-lines" instead of a glyph.

    python3 tools/gen_xml_icons.py

The names are the macro names without CUI_ICON_, lower case, with '-' for '_':
CUI_ICON_SKIP_FORWARD is "skip-forward". A name defined twice keeps its first
glyph. The file is checked in; run this again when the icons change.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "include", "cui", "cui_icons.h")
OUTPUT = os.path.join(ROOT, "src", "cui_xml_icons.h")

LINE = re.compile(r'^#define\s+CUI_ICON_([A-Z0-9_]+)\s+("(?:[^"\\]|\\.)*")\s*$')


def main():
    names = []
    seen = set()
    with open(SOURCE, encoding="utf-8") as f:
        for line in f:
            m = LINE.match(line.strip())
            if not m:
                continue
            name = m.group(1).lower().replace("_", "-")
            if name in seen:
                continue
            seen.add(name)
            names.append((name, m.group(2)))
    names.sort(key=lambda e: e[0])
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("/* Generated by tools/gen_xml_icons.py from include/cui/cui_icons.h.\n"
                  " * Do not edit: run the tool again.\n"
                  " *\n"
                  " * The icons a document can name: Icon=\"audio-lines\" is\n"
                  " * CUI_ICON_AUDIO_LINES. A name that is not here is passed to the\n"
                  " * renderer as it is, so a glyph written directly still works. */\n")
        out.write("#ifndef CUI_XML_ICONS_H\n#define CUI_XML_ICONS_H\n\n")
        out.write("typedef struct cui__xml_icon_entry { const char *name; const char *glyph; } "
                  "cui__xml_icon_entry;\n\n")
        out.write("static const cui__xml_icon_entry cui__xml_icons[] = {\n")
        for name, glyph in names:
            out.write('    { "%s", %s },\n' % (name, glyph))
        out.write("};\n\n#endif /* CUI_XML_ICONS_H */\n")
    print("%d icons -> %s" % (len(names), os.path.relpath(OUTPUT, ROOT)))


if __name__ == "__main__":
    main()
